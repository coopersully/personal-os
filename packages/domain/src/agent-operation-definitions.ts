import type { AgentCapability, AgentWorkspace } from "./agent-permissions.js";
import type { AccessScope } from "./auth.js";

export type AgentOperationDefinition = {
  legacyHumanOnly?: boolean;
  /** Granular material-reading selection for global domains outside the four workspaces. */
  connectionReadScopes?: readonly AccessScope[];
  /** OR alternatives only for bounded supporting reads; never applies to mutations. */
  supportingReadAnyCapability?: readonly AgentCapability[];
  readOnly: boolean;
  legacyScopes: readonly AccessScope[];
  scopeMatch: "any" | "all";
  capabilities: readonly AgentCapability[];
  workspace: AgentWorkspace | null;
  supportingRead: boolean;
  risk: "ordinary" | "dangerous";
};

export function agentOperationConnectionSelected(
  definition: AgentOperationDefinition,
  scopes: ReadonlySet<AccessScope>,
) {
  return (definition.connectionReadScopes ?? []).every((scope) => scopes.has(scope));
}
export function agentOperationRequiredCapabilities(
  definition: AgentOperationDefinition,
  policy: { capabilities: Record<AgentCapability, boolean> },
) {
  const alternatives =
    definition.readOnly && definition.supportingRead
      ? definition.supportingReadAnyCapability
      : undefined;
  const fallback = alternatives?.[0];
  if (alternatives && fallback)
    return [alternatives.find((capability) => policy.capabilities[capability]) ?? fallback];
  return definition.capabilities;
}

