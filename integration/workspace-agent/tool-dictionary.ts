import { readdir, readFile } from "node:fs/promises";
import { Client, InMemoryTransport } from "@modelcontextprotocol/client";
import type { PersonalOsApiClient } from "@personal-os/api-client";
import { accessScopeSchema } from "@personal-os/domain";
import { createPersonalOsMcpServer } from "../../apps/mcp/src/server.js";
import { type IloToolName, iloToolCatalog } from "../../apps/mcp/src/tool-catalog.js";

/** Discovery only. This deliberately cannot execute domain operations or count as runtime proof. */
export async function discoverToolDictionary() {
  const client = new Client({ name: "dictionary", version: "1" });
  const server = createPersonalOsMcpServer({
    api: {} as PersonalOsApiClient,
    scopes: new Set(accessScopeSchema.options),
    includeCompatibilityTools: true,
    timeZone: "UTC",
  });
  const [a, b] = InMemoryTransport.createLinkedPair();
  try {
    await Promise.all([client.connect(a), server.connect(b)]);
    const tools = (await client.listTools()).tools;
    return tools
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((tool) => ({ tool, definition: iloToolCatalog[tool.name as IloToolName] }));
  } finally {
    await Promise.allSettled([client.close(), server.close()]);
  }
}
export async function renderToolDictionary() {
  const sources = new Map<string, { path: string; methods: string[] }>();
  for (const name of await readdir("apps/mcp/src/tools")) {
    if (!name.endsWith(".ts") || name.endsWith(".test.ts")) continue;
    const source = await readFile(`apps/mcp/src/tools/${name}`, "utf8");
    const blocks = source.split(/server\.registerTool\(/).slice(1);
    for (const block of blocks) {
      const tool = block.match(/^\s*"([^"]+)"/);
      if (tool)
        sources.set(tool[1] ?? "", {
          path: `../../apps/mcp/src/tools/${name}`,
          methods: [
            ...new Set([...block.matchAll(/api\.([A-Za-z0-9_]+)\(/g)].map((m) => m[1] ?? "")),
          ],
        });
    }
  }
  const lines = [
    "# Workspace MCP tool dictionary",
    "",
    "Generated by `pnpm exec tsx scripts/workspace-agent-dictionary.ts`. Checked against live MCP discovery in the test suite. Descriptions and JSON input schemas are the executable interface contract; this file is discovery evidence, not proof that a query or provider operation succeeds. Clock-derived defaults are labeled <runtime date default>.",
    "",
    "Read [capabilities and verification](workspace-agent-capabilities.md) for policy, examples, owner-only exclusions, and actual runtime evidence. Existing compatibility tools are listed explicitly and hidden by default.",
    "",
  ];
  for (const { tool, definition } of await discoverToolDictionary()) {
    const source = sources.get(tool.name);
    lines.push(
      `## ${tool.name}`,
      "",
      tool.description ?? "",
      "",
      `- Domain: ${definition.domain}; stage: ${definition.stage}; policy: ${definition.policy}.`,
      `- Grants (${definition.scopeMatch ?? "any"}): ${definition.requiredScopes.join(", ") || "orientation only"}.`,
      `- Compatibility: ${definition.compatibility ? "hidden unless explicitly enabled" : "normal discovery"}; annotations: \`${JSON.stringify(tool.annotations)}\`.`,
      ...(source
        ? [
            `- [Adapter source](${source.path})${source.methods.length ? `; typed API methods: ${source.methods.map((m) => `\`${m}\``).join(", ")}` : " (delegates to the named workflow helper)"}.`,
          ]
        : []),
      "",
      "```json",
      JSON.stringify(
        tool.inputSchema,
        (key, value) =>
          key === "default" && typeof value === "string" && /^\d{4}-\d{2}-\d{2}(T.*)?$/.test(value)
            ? "<runtime date default>"
            : value,
        2,
      ),
      "```",
      "",
    );
  }
  return lines.join("\n");
}
