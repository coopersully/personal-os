import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { chromium } from "@playwright/test";

// Official full-color artwork is kept offline; source URLs are recorded beside each asset.
const brands = {
  Chase: "chase.svg",
  Discover: "discover.svg",
  "Wells Fargo": "wells-fargo.png",
  "American Express": "american-express.svg",
};
const logos = {};
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 96, height: 96 }, deviceScaleFactor: 1 });
  for (const [brand, file] of Object.entries(brands)) {
    const bytes = await readFile(
      resolve(import.meta.dirname, "../apps/api/src/fixtures/institution-artwork", file),
    );
    const source = `data:${file.endsWith(".svg") ? "image/svg+xml" : "image/png"};base64,${bytes.toString("base64")}`;
    await page.setContent(
      `<style>html,body{margin:0;background:white}img{display:block;width:88px;height:88px;margin:4px;object-fit:contain}</style><img src="${source}" />`,
    );
    await page.locator("img").evaluate((image) => image.decode());
    logos[brand] = {
      institutionId: `fixture-${brand.toLowerCase().replaceAll(" ", "-")}`,
      logo: `data:image/png;base64,${(await page.screenshot()).toString("base64")}`,
      primaryColor: null,
      url: null,
    };
  }
} finally {
  await browser.close();
}
const directory = resolve(import.meta.dirname, "../apps/api/src/fixtures");
await mkdir(directory, { recursive: true });
await writeFile(
  resolve(directory, "institution-branding.ts"),
  `// Generated by scripts/generate-fixture-institution-logos.mjs from official institution artwork.\n// Source/attribution: fixtures/institution-artwork/sources.json. Institution trademarks remain their owners’ property.\nexport const fixtureInstitutionBranding = ${JSON.stringify(logos, null, 2)} as const;\n`,
);
