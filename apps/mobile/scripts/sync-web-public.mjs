// Copies the shared web UI's static files into this Expo project's public directory, which the
// Expo web target serves at the site root (dev server and `expo export`). The copies are
// generated and ignored by Git; apps/web/public and the installed Geist font stay the source.
import { cp, mkdir, readdir, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const webRoot = resolve(appRoot, "../web");
const publicRoot = join(appRoot, "public");

// Generated by the web app's own build (service worker, public documents); not part of the UI.
const webOnly = new Set([
  "sw.js",
  "about",
  "docs",
  "privacy",
  "terms",
  "data-use",
  "sms",
  "support",
]);

export async function webPublicEntries(directory = join(webRoot, "public")) {
  const entries = await readdir(directory);
  return entries.filter((entry) => !webOnly.has(entry) && !entry.startsWith("workbox-")).sort();
}

export async function syncWebPublic() {
  const entries = await webPublicEntries();
  for (const entry of entries) {
    await rm(join(publicRoot, entry), { force: true, recursive: true });
    await cp(join(webRoot, "public", entry), join(publicRoot, entry), {
      dereference: true,
      recursive: true,
    });
  }
  const require = createRequire(join(webRoot, "package.json"));
  const geist = join(dirname(require.resolve("@fontsource-variable/geist/package.json")), "files");
  const fonts = join(publicRoot, "fonts", "geist");
  await rm(fonts, { force: true, recursive: true });
  await mkdir(dirname(fonts), { recursive: true });
  await cp(geist, fonts, { dereference: true, recursive: true });
  return [...entries, "fonts/geist"];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const synced = await syncWebPublic();
  console.log(`Synced ${synced.length} web public entries into apps/mobile/public.`);
}
