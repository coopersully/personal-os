import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { chromium } from "@playwright/test";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as registry from "../../web/src/components/icons";
import { workspacePalette } from "../src/navigation/workspace-palette.ts";

const glyphs = {
  index: "Sun",
  tasks: "ListChecks",
  mail: "Mail",
  finances: "Bank",
  calendar: "Calendar",
};
const directory = resolve(import.meta.dirname, "../assets/workspace-menu");
await mkdir(directory, { recursive: true });
const browser = await chromium.launch();
const entries = [];
try {
  const page = await browser.newPage({ viewport: { width: 24, height: 24 }, deviceScaleFactor: 3 });
  for (const [mode, palette] of Object.entries(workspacePalette)) {
    for (const [id, glyph] of Object.entries(glyphs)) {
      for (const filled of [false, true]) {
        const name = `${mode}-${id}-${filled ? "filled" : "outline"}`;
        const svg = renderToStaticMarkup(
          // biome-ignore lint/performance/noDynamicNamespaceImportAccess: canonical registry used at build time only.
          createElement(registry[`${glyph}Icon`], {
            weight: filled ? "Filled" : "Outline",
            color: filled ? palette[id] : palette.neutral,
          }),
        );
        await page.setContent(
          `<style>html,body{margin:0;background:transparent}svg{display:block}</style>${svg}`,
        );
        await writeFile(
          resolve(directory, `${name}.png`),
          await page.screenshot({ omitBackground: true }),
        );
        entries.push(`  "${name}": require("../../assets/workspace-menu/${name}.png"),`);
      }
    }
  }
} finally {
  await browser.close();
}
await writeFile(
  resolve(import.meta.dirname, "../src/components/workspace-menu-assets.ts"),
  `// Generated by scripts/generate-workspace-menu-icons.mjs.\nexport const workspaceMenuAssets = {\n${entries.join("\n")}\n};\n`,
);
