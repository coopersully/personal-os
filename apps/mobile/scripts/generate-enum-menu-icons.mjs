import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { chromium } from "@playwright/test";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as registry from "../../web/src/components/icons";

// UIKit extracts UIImage from menu labels, ignoring SwiftUI resizable/frame modifiers.
// Ship menu-sized, single-resolution artwork so UIImage(data:) cannot inflate @3x pixels.
const glyphs = {
  people: "Users",
  views: "ListTodo",
  tasks: "ListChecks",
  mail: "Mail",
  calendar: "Calendar",
  finances: "Bank",
};
const directory = resolve(import.meta.dirname, "../assets/enum-menu");
await mkdir(directory, { recursive: true });
const browser = await chromium.launch();
const entries = [];
try {
  const page = await browser.newPage({ viewport: { width: 20, height: 20 }, deviceScaleFactor: 1 });
  for (const [id, glyph] of Object.entries(glyphs)) {
    const tones = [];
    for (const [tone, color] of Object.entries({ light: "#202024", dark: "#fafafa" })) {
      const svg = renderToStaticMarkup(
        // biome-ignore lint/performance/noDynamicNamespaceImportAccess: build-time canonical icon registry.
        createElement(registry[`${glyph}Icon`], { color, size: 20 }),
      );
      await page.setContent(
        `<style>html,body{margin:0;background:transparent;color:${color}}svg{display:block;width:20px;height:20px}</style>${svg}`,
      );
      await writeFile(
        resolve(directory, `${id}-${tone}.png`),
        await page.screenshot({ omitBackground: true }),
      );
      tones.push(`${tone}: require("../../assets/enum-menu/${id}-${tone}.png")`);
    }
    entries.push(`  ${id}: { ${tones.join(", ")} },`);
  }
} finally {
  await browser.close();
}
await writeFile(
  resolve(import.meta.dirname, "../src/components/enum-menu-icons.ts"),
  `// Generated by scripts/generate-enum-menu-icons.mjs. Single-resolution UIKit menu artwork.\nimport type { ImageSourcePropType } from "react-native";\nimport type { IconName } from "./icons";\nexport const enumMenuIcons: Partial<Record<IconName, {light: ImageSourcePropType; dark: ImageSourcePropType}>> = {\n${entries.join("\n")}\n};\n`,
);
